mkdir -p "$DIR"
sed -n '/^__PAYLOAD__$/,$p' "$0" | tail -n +2 | base64 -d | tar -xz -C "$DIR" --strip-components=1
[ -f "$HERE/siat_dump.sql.gz" ] && cp "$HERE/siat_dump.sql.gz" "$DIR/deploy/" && echo "Найден дамп базы с Mac, использую его"
exec bash "$DIR/deploy/setup_server.sh" "$@"
