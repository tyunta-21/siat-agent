# SIAT AI Agent: one-shot setup on an Ubuntu server (AWS Lightsail / EC2 / any VPS).
#   sudo bash install_siat_server.sh          (first install or full update)
#   sudo bash install_siat_server.sh --code   (new code only: keeps the data, ~2 minutes)
# Puts the code in /opt/siat_agent and runs deploy/setup_server.sh (Docker, keys, data, bot, nightly update).
# If siat_dump.sql.gz (made on the Mac by deploy/export_from_mac.sh) lies next to this script,
# the database is restored from it instead of downloading everything from SIAT.
